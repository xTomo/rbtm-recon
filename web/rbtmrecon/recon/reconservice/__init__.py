"""recon-service — HTTP-сервис студии реконструкции (этап 2).

Запуск в образе reconstructor вместо ``tomo_worker.py``::

    gunicorn -w 1 -k gthread --threads 8 -b 0.0.0.0:5560 --timeout 600 'reconservice.app:create_app()'

Один процесс (``-w 1``): интерактивная сессия и очередь задач живут в его памяти.

Роли GPU (``CUDA_VISIBLE_DEVICES``):
- процесс сервиса видит только карту интерактивной сессии (на nanotom — GPU 1): превью срезов, ось, кольца;
- задачи реконструкции запускаются отдельным процессом ``python -m reconengine run`` с
  ``CUDA_VISIBLE_DEVICES=RECON_JOB_GPU`` (GPU 0) под ``flock(RECON_GPU_LOCK)`` — общим с Jupyter и старой
  очередью ноутбуков. Отдельный процесс нужен и потому, что astra выбирает GPU глобально на процесс, и ради
  чистой отмены (SIGTERM) и освобождения памяти после задачи.

Модули:
- ``config``   — настройки из окружения;
- ``auth``     — токен ``X-Recon-Token`` (общий секрет с rbtm-web), пользователь ``X-Recon-User``, проверка exp_id;
- ``binary``   — бинарные ответы (сырые LE-байты + ``X-Shape``, ``X-Dtype``, ``X-Scale``/``X-Offset``, ``X-Meta``);
- ``scans``    — сведения о скане и обзор без загрузки данных (``/scans/*``);
- ``sessions`` — одна интерактивная сессия: загрузка кропа, превью (``/sessions/*``);
- ``arbiter``  — «последний запрос выигрывает» для интерактивных каналов;
- ``preview``  — вычисления превью по кропу сессии (срез, ось, кольца);
- ``jobs``     — очередь задач в Mongo ``autotom.jobs``, запуск движка, отмена (``/jobs/*``);
- ``publish``  — перенос результата в ``/storage/<id>/reconstruction/``, история, архивная копия ``.h5``;
- ``results``  — результат: сведения, срезы копии ×4, файлы (``/results/*``);
- ``cache``    — предел кэша кропов на /fast (``RECON_FAST_LIMIT_GB``): вытеснение давно не использованных;
- ``prefetch`` — предзагрузка исходного HDF5 (HDD) в кэш ОС после обзора, до «Загрузить область» (``RECON_PREFETCH``);
- ``app``      — сборка Flask-приложения, ``/health``;
- ``preflight`` — проверка окружения после выкатки: ``python -m reconservice.preflight [--exp <id>]``.

Права (кто может загружать, запускать, отменять) проверяет rbtm-web; сервис доверяет запросам с верным токеном
и берёт имя пользователя из ``X-Recon-User`` (владелец сессии, автор задачи).
"""
